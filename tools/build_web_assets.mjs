#!/usr/bin/env node
/**
 * build_web_assets.mjs — bake `assets/billboards/` (manifest + PNG sprite sheets)
 * into `web_preview/billboard_assets.js`, an ES module consumed by the Three.js
 * web preview.  PNGs are inlined as base64 data URLs so the page has zero
 * runtime network dependencies beyond its own local files.
 *
 * Usage:
 *   node tools/build_web_assets.mjs            # build from assets/billboards/
 *   node tools/build_web_assets.mjs --check    # fail (exit 1) if output is stale
 *
 * Output schema (docs/3d-render-spec.md §3.1, §5):
 *   export const CAPTURE_SCALE: number
 *   export const FRAME_W: number
 *   export const FRAME_H: number
 *   export const PLACEHOLDER: boolean     // true when no manifest was found
 *   export const SHEETS: { [name]: { file, frames, fps, anchor, bbox, src } }
 */
import { readFile, writeFile, stat } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ASSET_DIR = path.join(ROOT, 'assets', 'billboards');
const MANIFEST_PATH = path.join(ASSET_DIR, 'manifest.json');
const OUT_PATH = path.join(ROOT, 'web_preview', 'billboard_assets.js');

const CHECK = process.argv.includes('--check');

const HEADER = `// AUTO-GENERATED FILE — DO NOT EDIT BY HAND.
// Generated by tools/build_web_assets.mjs from assets/billboards/manifest.json.
// Re-run:  node tools/build_web_assets.mjs
`;

/** Read width/height from a PNG IHDR chunk (used for sanity checks). */
function pngSize(buf) {
  if (buf.length < 24) return null;
  const sig = [0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a];
  for (let i = 0; i < 8; i++) if (buf[i] !== sig[i]) return null;
  return { width: buf.readUInt32BE(16), height: buf.readUInt32BE(20) };
}

function moduleFor({ captureScale, frameW, frameH, sheets, placeholder, reason }) {
  const lines = [];
  lines.push(HEADER);
  if (reason) lines.push(`// NOTE: ${reason}`);
  lines.push(`export const CAPTURE_SCALE = ${JSON.stringify(captureScale)};`);
  lines.push(`export const FRAME_W = ${JSON.stringify(frameW)};`);
  lines.push(`export const FRAME_H = ${JSON.stringify(frameH)};`);
  lines.push(`export const PLACEHOLDER = ${placeholder ? 'true' : 'false'};`);
  lines.push('export const SHEETS = {');
  const names = Object.keys(sheets).sort();
  for (const name of names) {
    const s = sheets[name];
    const json = JSON.stringify(
      { file: s.file, frames: s.frames, fps: s.fps, anchor: s.anchor, bbox: s.bbox, src: s.src },
      null,
      0
    );
    lines.push(`  ${JSON.stringify(name)}: ${json},`);
  }
  lines.push('};');
  lines.push('');
  return lines.join('\n');
}

async function main() {
  // ---- placeholder mode: the billboard baker has not produced anything yet ----
  if (!existsSync(MANIFEST_PATH)) {
    const mod = moduleFor({
      captureScale: 2.0,
      frameW: 256,
      frameH: 256,
      sheets: {},
      placeholder: true,
      reason: `assets/billboards/manifest.json not found — the web preview will draw placeholder billboards. Re-run this script once the lead has baked the sprite sheets.`,
    });
    if (CHECK) {
      console.error('[build_web_assets] MISSING manifest: assets/billboards/manifest.json');
      process.exit(1);
    }
    await writeFile(OUT_PATH, mod, 'utf8');
    console.warn('[build_web_assets] no manifest yet — wrote PLACEHOLDER billboard_assets.js');
    return;
  }

  const manifest = JSON.parse(await readFile(MANIFEST_PATH, 'utf8'));
  const captureScale = Number(manifest.capture_scale) || 2.0;
  const frameW = Number(manifest.frame_w) || 256;
  const frameH = Number(manifest.frame_h) || 256;
  const srcSheets = manifest.sheets || {};

  const sheets = {};
  const warnings = [];
  let totalBytes = 0;
  for (const [name, def] of Object.entries(srcSheets).sort(([a], [b]) => a.localeCompare(b))) {
    const file = def.file;
    const pngPath = path.join(ASSET_DIR, file);
    if (!file || !existsSync(pngPath)) {
      warnings.push(`missing PNG for sheet "${name}" (${file}) — skipped`);
      continue;
    }
    const buf = await readFile(pngPath);
    totalBytes += buf.length;
    const size = pngSize(buf);
    const frames = Math.max(1, Number(def.frames) || 1);
    if (size) {
      const expectW = frameW * frames;
      if (size.width !== expectW || size.height !== frameH) {
        warnings.push(
          `sheet "${name}": PNG is ${size.width}x${size.height}, expected ` +
            `${expectW}x${frameH} (frame_w=${frameW} * frames=${frames})`
        );
      }
    } else {
      warnings.push(`sheet "${name}": ${file} does not look like a PNG`);
    }
    sheets[name] = {
      file,
      frames,
      fps: Number(def.fps) || 1.0,
      anchor: Array.isArray(def.anchor) ? def.anchor.map(Number) : [frameW / 2, frameH],
      bbox: Array.isArray(def.bbox) ? def.bbox.map(Number) : [0, 0, frameW, frameH],
      src: `data:image/png;base64,${buf.toString('base64')}`,
    };
  }

  const mod = moduleFor({
    captureScale,
    frameW,
    frameH,
    sheets,
    placeholder: Object.keys(sheets).length === 0,
    reason: warnings.length ? `WARNINGS: ${warnings.join(' | ')}` : null,
  });

  // ---- --check: compare content (ignoring the header timestamp-free output) ----
  if (CHECK) {
    if (!existsSync(OUT_PATH)) {
      console.error('[build_web_assets] MISSING output web_preview/billboard_assets.js — run the script.');
      process.exit(1);
    }
    const current = await readFile(OUT_PATH, 'utf8');
    if (current !== mod) {
      console.error('[build_web_assets] STALE output — re-run node tools/build_web_assets.mjs');
      process.exit(1);
    }
    console.log('[build_web_assets] up to date.');
    return;
  }

  await writeFile(OUT_PATH, mod, 'utf8');
  const outSize = (await stat(OUT_PATH)).size;
  for (const w of warnings) console.warn(`[build_web_assets] WARN: ${w}`);
  console.log(
    `[build_web_assets] wrote ${path.relative(ROOT, OUT_PATH)} — ${Object.keys(sheets).length} sheets, ` +
      `${(totalBytes / 1024).toFixed(0)} KiB PNG -> ${(outSize / 1024).toFixed(0)} KiB module`
  );
}

main().catch((err) => {
  console.error('[build_web_assets] FAILED:', err);
  process.exit(1);
});
